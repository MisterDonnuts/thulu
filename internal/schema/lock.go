const LockPath = "internal/schema/migrations.lock"

type Lock struct {
	Releases []string
	Entries  []LockEntry
}

type LockEntry struct {
	Component  string
	ID         int
	SHA256     string
	ReleasedIn string
}

func (e LockEntry) Key() string { return e.Component + "/" + strconv.Itoa(e.ID) }

func entryKey(component string, id int) string { return component + "/" + strconv.Itoa(id) }

//i18n:ignore the lock file's own header: Format must write the same bytes in every locale
const lockHeader = `# Migrations lock. Generated by cmd/migrations; do not edit by hand.
#
# "release X" lines are the releases cut so far. Each other line is one
# migration: component, ID, sha256 of its SQL, and the release it first shipped
# in ("-" until it ships). A shipped migration never changes and never goes
# away; CI compares this file with the one on the base branch to enforce it.
#
#   make migrations-lock                 refresh the unreleased lines
#   make migrations-release VERSION=x    mark them shipped in x (release PR)
`

func ParseLock(r io.Reader) (*Lock, error) {
	l := &Lock{}
	seen := map[string]bool{}
	sc := bufio.NewScanner(r)
	n := 0
	for sc.Scan() {
		n++
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		if f[0] == "release" {
			r, err := parseRelease(f)
			if err != nil {
				return nil, apperr.Wrap(err, "schema.errors.lock_line", "line", n)
			}
			l.Releases = append(l.Releases, r)
			continue
		}
		e, err := parseEntry(f)
		if err != nil {
			return nil, apperr.Wrap(err, "schema.errors.lock_line", "line", n)
		}
		if seen[e.Key()] {
			return nil, apperr.Invalid("schema.errors.lock_line_duplicate", "line", n, "migration", e.Key())
		}
		seen[e.Key()] = true
		l.Entries = append(l.Entries, e)
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	for _, e := range l.Entries {
		if e.ReleasedIn != "" && !l.hasRelease(e.ReleasedIn) {
			return nil, apperr.Invalid("schema.errors.released_in_unlisted", "migration", e.Key(), "release", e.ReleasedIn)
		}
	}
	return l, nil
}

func parseRelease(f []string) (string, error) {
	if len(f) != 2 {
		return "", apperr.Invalid("schema.errors.want_release_line")
	}
	return f[1], validRelease(f[1])
}

func parseEntry(f []string) (LockEntry, error) {
	if len(f) != 4 {
		return LockEntry{}, apperr.Invalid("schema.errors.want_entry_line")
	}
	id, err := strconv.Atoi(f[1])
	if err != nil || id <= 0 {
		return LockEntry{}, apperr.Invalid("schema.errors.bad_id", "id", f[1])
	}
	if len(f[2]) != 64 {
		return LockEntry{}, apperr.Invalid("schema.errors.bad_sha256", "sha", f[2])
	}
	e := LockEntry{Component: f[0], ID: id, SHA256: f[2]}
	if f[3] != "-" {
		e.ReleasedIn = f[3]
	}
	return e, nil
}

func (l *Lock) Format() []byte {
	var b bytes.Buffer
	b.WriteString(lockHeader)
	b.WriteString("\n")
	for _, r := range l.Releases {
		fmt.Fprintf(&b, "release %s\n", r) //i18n:ignore lock file syntax, not a message
	}
	if len(l.Releases) > 0 {
		b.WriteString("\n")
	}
	entries := append([]LockEntry(nil), l.Entries...)
	sortEntries(entries)
	for _, e := range entries {
		rel := e.ReleasedIn
		if rel == "" {
			rel = "-"
		}
		fmt.Fprintf(&b, "%s %d %s %s\n", e.Component, e.ID, e.SHA256, rel)
	}
	return b.Bytes()
}

func sortEntries(es []LockEntry) {
	sort.SliceStable(es, func(i, j int) bool {
		if es[i].Component != es[j].Component {
			return es[i].Component < es[j].Component
		}
		return es[i].ID < es[j].ID
	})
}

func validRelease(s string) error {
	v, ok := semver.Parse(s)
	if !ok || v.String() != s || v.Build != "" {
		return apperr.Invalid("schema.errors.not_release_version", "version", s)
	}
	return nil
}

func (l *Lock) hasRelease(v string) bool {
	for _, r := range l.Releases {
		if r == v {
			return true
		}
	}
	return false
}

func (l *Lock) Latest() string {
	latest := ""
	for _, r := range l.Releases {
		if latest == "" || semver.Newer(r, latest) {
			latest = r
		}
	}
	return latest
}

func (l *Lock) byKey() map[string]LockEntry {
	m := make(map[string]LockEntry, len(l.Entries))
	for _, e := range l.Entries {
		m[e.Key()] = e
	}
	return m
}

type Problems []string

func (p Problems) Err() error {
	if len(p) == 0 {
		return nil
	}
	return errors.New(strings.Join(p, "\n"))
}

func Check(l *Lock, all []Entry) Problems {
	var p Problems
	locked := l.byKey()
	inCode := map[string]bool{}
	for _, e := range all {
		k := entryKey(e.Component, e.ID)
		inCode[k] = true
		le, ok := locked[k]
		switch {
		case !ok:
			p = append(p, i18n.Text("schema.problems.not_in_lock", "migration", k))
		case le.SHA256 != e.SHA256 && le.ReleasedIn != "":
			p = append(p, i18n.Text("schema.problems.shipped_sql_changed", "migration", k, "release", le.ReleasedIn))
		case le.SHA256 != e.SHA256:
			p = append(p, i18n.Text("schema.problems.changed_since_lock", "migration", k))
		}
		if e.Contract != nil {
			if err := validRelease(e.Contract.StoppedUsingIn); err != nil {
				p = append(p, i18n.Text("schema.problems.contract_release_invalid", "migration", k, "err", apperr.Text(err)))
			}
			if strings.TrimSpace(e.Contract.Reason) == "" {
				p = append(p, i18n.Text("schema.problems.contract_reason_empty", "migration", k))
			}
		}
	}
	for _, le := range l.Entries {
		if inCode[le.Key()] {
			continue
		}
		if le.ReleasedIn != "" {
			p = append(p, i18n.Text("schema.problems.shipped_gone", "migration", le.Key(), "release", le.ReleasedIn))
		} else {
			p = append(p, i18n.Text("schema.problems.lock_only", "migration", le.Key()))
		}
	}
	return p
}

func CheckAgainstBase(l, base *Lock) Problems {
	var p Problems
	for _, r := range base.Releases {
		if !l.hasRelease(r) {
			p = append(p, i18n.Text("schema.problems.release_removed", "release", r))
		}
	}
	cur := l.byKey()
	for _, be := range base.Entries {
		if be.ReleasedIn == "" {
			continue
		}
		e, ok := cur[be.Key()]
		switch {
		case !ok:
			p = append(p, i18n.Text("schema.problems.shipped_removed_from_lock", "migration", be.Key(), "release", be.ReleasedIn))
		case e.SHA256 != be.SHA256:
			p = append(p, i18n.Text("schema.problems.shipped_hash_changed", "migration", be.Key(), "release", be.ReleasedIn))
		case e.ReleasedIn != be.ReleasedIn:
			p = append(p, i18n.Text("schema.problems.shipped_release_changed", "migration", be.Key(), "release", be.ReleasedIn, "now", e.ReleasedIn))
		}
	}
	if latest := base.Latest(); latest != "" {
		for _, r := range l.Releases {
			if !base.hasRelease(r) && !semver.Newer(r, latest) {
				p = append(p, i18n.Text("schema.problems.release_not_newer_than_base", "release", r, "latest", latest))
			}
		}
	}
	return p
}

func Relock(l *Lock, all []Entry) (*Lock, error) {
	locked := l.byKey()
	next := &Lock{Releases: append([]string(nil), l.Releases...)}
	inCode := map[string]bool{}
	var p Problems
	for _, e := range all {
		k := entryKey(e.Component, e.ID)
		inCode[k] = true
		le, ok := locked[k]
		if ok && le.ReleasedIn != "" {
			if le.SHA256 != e.SHA256 {
				p = append(p, i18n.Text("schema.problems.relock_sql_changed", "migration", k, "release", le.ReleasedIn))
			}
			next.Entries = append(next.Entries, le)
			continue
		}
		next.Entries = append(next.Entries, LockEntry{Component: e.Component, ID: e.ID, SHA256: e.SHA256})
	}
	for _, le := range l.Entries {
		if le.ReleasedIn != "" && !inCode[le.Key()] {
			p = append(p, i18n.Text("schema.problems.relock_gone", "migration", le.Key(), "release", le.ReleasedIn))
		}
	}
	if err := p.Err(); err != nil {
		return nil, err
	}
	return next, nil
}

func MarkReleased(l *Lock, version string) (*Lock, error) {
	if err := validRelease(version); err != nil {
		return nil, err
	}
	if l.hasRelease(version) {
		return nil, apperr.Conflict("schema.errors.release_already_listed", "release", version)
	}
	if latest := l.Latest(); latest != "" && !semver.Newer(version, latest) {
		return nil, apperr.Invalid("schema.errors.release_not_newer", "release", version, "latest", latest)
	}
	next := &Lock{Releases: append(append([]string(nil), l.Releases...), version)}
	for _, e := range l.Entries {
		if e.ReleasedIn == "" {
			e.ReleasedIn = version
		}
		next.Entries = append(next.Entries, e)
	}
	return next, nil
}

func CheckReady(l *Lock, version string) Problems {
	var p Problems
	if !l.hasRelease(version) {
		p = append(p, i18n.Text("schema.problems.release_not_listed", "release", version))
	}
	for _, e := range l.Entries {
		if e.ReleasedIn == "" {
			p = append(p, i18n.Text("schema.problems.not_shipped", "migration", e.Key()))
		}
	}
	return p
}
